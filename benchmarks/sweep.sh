#!/usr/bin/env bash
# benchmarks/sweep.sh — sweep one AiProps value across mirror matchups and
# collect win rates into a CSV, for calibrating sim-engine evaluator weights.
#
# For each value, generates a throwaway profile forge-gui/res/ai/Sweep_<PARAM>_<v>.ai
# (base profile + appended override; AiProfileUtil keeps the last occurrence of a
# key) and runs seat 1 as "sim:<profile>" against a fixed opponent profile.
#
# Usage:
#   benchmarks/sweep.sh <PARAM> <v1,v2,...> [-d DECK]... [-n N] [-j J] \
#                       [-o OPPONENT_PROFILE] [--base BASE_PROFILE] [-B BASE_DIR] [-c SECS]
#
# Examples:
#   benchmarks/sweep.sh SIM_EVAL_LIFE_PRESSURE_WEIGHT 0,20,45,80 -n 20 -j 8
#   benchmarks/sweep.sh SIM_PLAN_SCORE_TOLERANCE 0,40,80,160 -d Burn.dck -n 20
#
set -euo pipefail

if [[ $# -lt 2 ]]; then
    sed -n '2,17p' "$0"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
RESULTS_DIR="$SCRIPT_DIR/results"
PROFILE_DIR="$REPO_ROOT/forge-gui/res/ai"
mkdir -p "$RESULTS_DIR"

PARAM="$1"; shift
IFS=',' read -r -a VALUES <<< "$1"; shift

DECKS=()
N=20
J=8
OPP="Default"
BASE_PROFILE="Enhanced"
BASE_DIR="user/decks"
TIMEOUT=900

while [[ $# -gt 0 ]]; do
    case "$1" in
        -d) DECKS+=("$2"); shift 2 ;;
        -n) N="$2"; shift 2 ;;
        -j) J="$2"; shift 2 ;;
        -o) OPP="$2"; shift 2 ;;
        --base) BASE_PROFILE="$2"; shift 2 ;;
        -B) BASE_DIR="$2"; shift 2 ;;
        -c) TIMEOUT="$2"; shift 2 ;;
        *) echo "Unknown arg: $1" >&2; exit 1 ;;
    esac
done

if [[ ${#DECKS[@]} -eq 0 ]]; then
    DECKS=("Burn.dck" "White Weenie.dck")
fi

if [[ ! -f "$PROFILE_DIR/$BASE_PROFILE.ai" ]]; then
    echo "Error: base profile not found: $PROFILE_DIR/$BASE_PROFILE.ai" >&2
    exit 1
fi

# Generated profiles are visible to any concurrently-started Forge instance;
# always clean them up, even on Ctrl-C.
cleanup() { rm -f "$PROFILE_DIR"/Sweep_*.ai; }
trap cleanup EXIT

slug() { echo "$1" | tr ':/ @' '____' | tr -dc 'a-zA-Z0-9_.-'; }
TS="$(date +%Y%m%d-%H%M%S)"
CSV="$RESULTS_DIR/sweep-$(slug "$PARAM")-$TS.csv"
echo "param,value,deck,opponent,n,completed,wins,losses,draws,winrate_pct,avg_ms" > "$CSV"

echo "==> sweep: $PARAM over [${VALUES[*]}]  decks=${DECKS[*]}  n=$N j=$J opp=$OPP base=$BASE_PROFILE" >&2
echo "==> csv: $CSV" >&2

cd "$REPO_ROOT"

for v in "${VALUES[@]}"; do
    PROF="Sweep_${PARAM}_$(slug "$v")"
    {
        echo "# generated by benchmarks/sweep.sh — safe to delete"
        cat "$PROFILE_DIR/$BASE_PROFILE.ai"
        echo ""
        echo "$PARAM=$v"
    } > "$PROFILE_DIR/$PROF.ai"

    for deck in "${DECKS[@]}"; do
        DECK_SLUG="$(slug "$(basename "$deck" .dck)")"
        OUT_FILE="$RESULTS_DIR/sweep-$(slug "$PARAM")-$(slug "$v")-$DECK_SLUG-$TS.json"
        echo "==> $PARAM=$v deck=$deck ..." >&2
        ./run.sh --run-only -d "$deck" -d "$deck" -B "$BASE_DIR" -n "$N" -j "$J" \
            -c "$TIMEOUT" -q --json -P "1:sim:$PROF" -P "2:$OPP" 2>/dev/null \
            | sed -n '/^{/,$p' > "$OUT_FILE"

        python3 - "$OUT_FILE" "$PARAM" "$v" "$deck" "$OPP" >> "$CSV" <<'PY'
import json, sys
path, param, value, deck, opp = sys.argv[1:6]
with open(path) as f:
    d = json.load(f)
s = d["summary"]
p1 = next(p for p in s["players"] if p["playerIndex"] == 0)
wins = p1.get("wins", 0)
losses = p1.get("losses", 0)
print(f'{param},{value},{deck},{opp},{s["totalGames"]},{s.get("completedGames", s["totalGames"])},'
      f'{wins},{losses},{s["draws"]},{p1.get("winRate", 0.0):.1f},{s.get("averageGameTimeMs", 0):.0f}')
PY
        tail -1 "$CSV" >&2
    done
done

echo "==> sweep complete: $CSV" >&2
